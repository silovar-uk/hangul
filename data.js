export const ALL_ITEMS = STAGES.flatMap((stage) =>
  stage.items.map((entry) => ({ ...entry, stageId: stage.id, stageNumber: stage.number }))
);

export function getStage(stageId) {
  return STAGES.find((stage) => stage.id === stageId);
}
